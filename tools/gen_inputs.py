#!/usr/bin/env python3
"""Write the pad scripts in tools/inputs/ (tools/src/mdtrace.c's format).

    tools/gen_inputs.py

Each script starts from power-on and steers through the menus with fixed
presses, then plays with seeded pseudo-random input, so a run is the same
every time.  In play, Start is pressed in pairs a few frames apart: on a
screen that waits for Start the first press moves on, in a stage the pair
pauses and unpauses.

The menu timings are us's (eu's are close; check with screenshots).
"""
import os
import random

HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'inputs')

# us: the title menu waits from about frame 2700; Start at 2400 skips the
# intro, Start at 3300 takes the highlighted entry
TITLE = [(2400, 1, 'S'), (2405, 1, '-'), (2700, 1, 'S'), (2705, 1, '-')]


def press(ev, frame, pad, buttons, hold=6):
    ev.append((frame, pad, buttons))
    ev.append((frame + hold, pad, '-'))


def play(ev, rng, start, end, pads=(1,), bomb='C', extra='AB', every=40):
    """Random walking with bombs from start to end, on each pad."""
    for pad in pads:
        f = start + rng.randrange(every)
        while f < end:
            d = rng.choice('UDLR')
            b = ''
            r = rng.random()
            if r < 0.35:
                b = bomb
            elif r < 0.45:
                b = rng.choice(extra)
            hold = rng.randrange(8, every)
            ev.append((f, pad, d + b))
            if b:
                ev.append((f + 4, pad, d))
            f += hold
            if rng.random() < 0.02:
                press_pair(ev, f, pad)
                f += 30
        ev.append((end, pad, '-'))


def press_pair(ev, f, pad):
    press(ev, f, pad, 'S', 4)
    press(ev, f + 12, pad, 'S', 4)


def write(name, ev, comment, frames=None, compare=None, teamplayer=False,
          wayplay=False):
    """frames: how long the script runs (a `# frames N` line, which
    tools/trace_all.sh and tools/shift_check.py read); compare: the frame
    tools/shift_check.py compares up to (`# compare N`); teamplayer: run
    with Sega's Team Player (`# teamplayer`); wayplay: with EA's 4-Way
    Play (`# wayplay`)."""
    ev.sort(key=lambda e: (e[0], e[1]))
    with open(os.path.join(HERE, name), 'w') as f:
        for line in comment.strip().split('\n'):
            f.write('# %s\n' % line)
        f.write('# generated by tools/gen_inputs.py\n')
        if frames:
            f.write('# frames %d\n' % frames)
        if compare:
            f.write('# compare %d\n' % compare)
        if teamplayer:
            f.write('# teamplayer\n')
        if wayplay:
            f.write('# wayplay\n')
        last = {}
        for frame, pad, b in ev:
            if not pad:
                f.write('%d %s\n' % (frame, b))     # a RAM write
                continue
            if last.get(pad) == b:
                continue
            last[pad] = b
            f.write('%d %d:%s\n' % (frame, pad, b))


def normal():
    rng = random.Random(1)
    ev = list(TITLE)
    press(ev, 3300, 1, 'S', 10)       # NORMAL GAME
    press(ev, 3600, 1, 'S', 10)       # past the area map
    f = 3900
    end = 60000
    # every 1500 frames a pair of Starts gets past stage cards, game overs
    # and continue screens; between them, random play
    while f < end:
        press_pair(ev, f, 1)
        play(ev, rng, f + 40, min(f + 1500, end))
        f += 1500
    write('normal.txt', ev, '''
Normal game from power-on: Start through the intro and the title menu
(NORMAL GAME), then random walking and bombs (C), with A and B now and
then, and a pair of Starts every 1500 frames for the screens that wait.''')


def battle(name, seed, pads, teamplayer, wayplay=False):
    write(name, battle_events(seed, pads), '''
Battle game from power-on%s: the title menu's BATTLE GAME, then cycles of
setup presses (C and Start in turn, a direction now and then) and random
play on pads %s (C is the bomb).''' % (
        ' with the Team Player' if teamplayer else
        ' with the 4-Way Play' if wayplay else '',
        ', '.join(map(str, pads))), teamplayer=teamplayer, wayplay=wayplay)


def battle_events(seed, pads):
    rng = random.Random(seed)
    ev = list(TITLE)
    press(ev, 3300, 1, 'D', 6)        # BATTLE GAME
    press(ev, 3400, 1, 'S', 10)
    f = 3700
    end = 60000
    while f < end:
        # the setup screens (combatants, games, MAN/COM and character,
        # stage) take C, the type screen Start, the stage select C: alternate
        # them, with a direction now and then (which also turns players
        # into COM), then play
        for k in range(20):
            b = 'S' if k % 2 else 'C'
            if rng.random() < 0.25:
                b = rng.choice('UDLR')
            press(ev, f + k * 45, 1, b)
        f += 20 * 45
        play(ev, rng, f, min(f + 2400, end), pads=pads)
        f += 2400
    return ev


# battle arenas (0x953A, the record of D_00A04A it plays on) the battle
# scripts' setup presses never pick: (arena, base script, the frame its
# first stage select has set 0x953A).  6 isn't one (its record shows
# garbage), 7 and 12 only come up with four players.
ARENAS = [(0, 2, 6500), (1, 2, 6500), (2, 2, 6500), (3, 2, 6500),
          (5, 2, 6500), (9, 2, 6500), (12, 4, 4370)]


def arenas():
    for arena, players, f in ARENAS:
        if players == 2:
            ev = battle_events(2, (1, 2))
        else:
            ev = battle_events(4, (1, 2, 3, 4))
        poke(ev, f, 0xFF953A, arena)
        write('arena-%02d.txt' % arena, ev, '''
Battle arena %d, which the battle scripts' setup never picks: battle%s.txt
with 0x953A written after its first stage select; 9000 frames.''' % (
            arena, '4' if players == 4 else ''), 9000,
            teamplayer=players == 4)


def password():
    rng = random.Random(3)
    ev = list(TITLE)
    press(ev, 3300, 1, 'D', 6)
    press(ev, 3340, 1, 'D', 6)        # PASSWORD
    press(ev, 3400, 1, 'S', 10)
    f = 3700
    for k in range(400):
        press(ev, f, 1, rng.choice('UDLRUDLRCCB') if k % 50 else 'S')
        f += 20
    write('password.txt', ev, '''
The title menu's PASSWORD, then random moves and letters (C), B to
delete, and Start every 50 presses.''')


# Normal game's passwords, from Sega Retro's Mega_Bomberman/Passwords (all
# checked in the emulator): each starts that stage with the default stock
PASSWORDS = [
    ('1-1', '2200'), ('1-2', '6800'), ('1-3', '5120'), ('1-boss', '7420'),
    ('2-1', '4501'), ('2-2', '8111'), ('2-3', '7421'), ('2-4', '1051'),
    ('2-boss', '3351'),
    ('3-1', '4502'), ('3-2', '8112'), ('3-3', '7422'), ('3-4', '1052'),
    ('3-boss', '3352'),
    ('4-1', '6803'), ('4-2', '0513'), ('4-3', '9723'), ('4-4', '3353'),
    ('4-boss', '5653'),
    ('5-1', '8114'), ('5-2', '2814'), ('5-3', '1134'), ('5-4', '5654'),
    ('5-boss', '7954'),
    ('final', '0515'),
]


def enter_password(ev, code, f):
    """On the password screen (0-0-0-0, the first digit selected): Up
    counts a digit up, Right moves to the next, Start confirms."""
    for i, c in enumerate(code):
        for _ in range(int(c)):
            press(ev, f, 1, 'U', 4)
            f += 12
        if i < 3:
            press(ev, f, 1, 'R', 4)
            f += 12
    press(ev, f + 30, 1, 'S', 6)
    return f + 30


def stages(frames=20000):
    for name, code in PASSWORDS:
        rng = random.Random(int(code))
        ev = list(TITLE)
        press(ev, 3300, 1, 'D', 6)
        press(ev, 3340, 1, 'D', 6)        # PASSWORD
        press(ev, 3400, 1, 'S', 10)
        f = enter_password(ev, code, 3700)
        press(ev, f + 300, 1, 'S', 6)     # past the area map
        f += 600
        while f < frames:
            press_pair(ev, f, 1)
            play(ev, rng, f + 40, min(f + 1500, frames))
            f += 1500
        write('stage-%s.txt' % name, ev, '''
Normal game from password %s (%s), then random play as in normal.txt.
''' % (code, name))


# work RAM (docs/LAYOUT.md, "Runtime traces"): object slots are 0x40 bytes
# from 0xFFA432 (func_001CFA), slot 0 the player; a slot's energy is +0x11
SLOT, ENERGY = 0xFFA432, 0x11


def poke(ev, frame, addr, value, digits=2):
    """A RAM write (mdtrace's `FRAME =ADDR VALUE`), sorted in with the pad
    lines (pad 0 sorts first)."""
    ev.append((frame, 0, '=%06X %0*X' % (addr, digits, value)))


def energy(ev, frame, slot, value):
    poke(ev, frame, SLOT + 0x40 * slot + ENERGY, value)


def ending():
    """The last room of the final area, the final boss and the ending, with
    RAM writes for what random play can't do.  Every write is a number
    (no ROM address), so the shifted build gets the same ones."""
    write('ending.txt', ending_events(), '''
Normal game from password 0515 (the final area) to the ending, with RAM
writes (`FRAME =ADDR VALUE`) for what random play can't do: room 5, the
room's targets and enemies, the player into the open gate, the player's
energy, and each form of the final boss.  us's timings and RAM.''', 24000)
    # each form left alone for a while: what it does that the ending
    # doesn't wait for (form 1's func_013638, form 3's func_012F4C and
    # func_012E5A)
    for form, cut, frames in ((1, 5800, 14000), (3, 11800, 20000)):
        write('final-form%d.txt' % form,
              [e for e in ending_events() if e[0] < cut], '''
ending.txt up to frame %d, then the final boss's form %d left to itself,
the player at 0x7F hits.''' % (cut, form), frames)


def ending_events():
    ev = list(TITLE)
    press(ev, 3300, 1, 'D', 6)
    press(ev, 3340, 1, 'D', 6)        # PASSWORD
    press(ev, 3400, 1, 'S', 10)
    f = enter_password(ev, '0515', 3700)
    press(ev, f + 300, 1, 'S', 6)     # past the area map
    press_pair(ev, f + 600, 1)        # the final area's screen (func_017C2A)
    # loc_0098F8 set room 0 (0x953E) and its stage number (0x953F,
    # func_009966) at 4529: room 5 instead, the one before the boss
    poke(ev, 4530, 0xFF953E, 5)
    poke(ev, 4530, 0xFF953F, 0x25 + 5)
    # the room's two targets (slots 6, 7) and its enemies: energy 0 is dead
    # (func_006E28); with the targets gone the gate opens (0x9540 bit 5)
    for slot in range(6, 18):
        energy(ev, 5000, slot, 0)
    # the player below the gate (0xA44A/0xA44C, slot 0's position), walking
    # up into it: the boss stage (0x30)
    poke(ev, 5250, 0xFFA44A, 0x80, 4)
    poke(ev, 5250, 0xFFA44C, 0x38, 4)
    press(ev, 5260, 1, 'U', 240)
    # the player takes 0x7F hits (func_003032), as with the heart item
    energy(ev, 5300, 0, 0x7F)
    # the boss's first form: its four orbs (slots 7-10)
    for slot in range(7, 11):
        energy(ev, 5800, slot, 0)
    # the second form (slot 8, func_014F46) loses a point per hit on slot 7:
    # one left
    energy(ev, 7100, 8, 1)
    # and the hit: an explosion (cell value 3, func_006E82) in the grid cell
    # (0xFF989C + row) at slot 7's position at 7250, not flashing.  No
    # explosion owns the cell, so it stays until slot 7 comes back over
    # it, around 10200
    poke(ev, 7250, SLOT + 0x40 * 7 + 0x12, 0)
    poke(ev, 7250, 0xFF9917, 3)
    # the last form (func_012CBC): energy 0 is its end (func_006E28), then
    # the escape (func_0139DC), the ending (0x953B = 6) and the credits
    # (func_015FAE's script, D_016FFA)
    energy(ev, 11800, 6, 0)
    return ev


# tools/find_exits.py's plans: each stage from its password to its exit
EXITS = os.path.join(os.path.dirname(HERE), 'exits.json')


def exit_events(code, plan):
    """A stage from its password through a tools/find_exits.py plan:
    Start on the screens that wait, energy 0 for the object slots 1-19
    (the room's enemies and targets), the player put next to the open
    gate on a cell made floor and walking in."""
    ev = list(TITLE)
    press(ev, 3300, 1, 'D', 6)
    press(ev, 3340, 1, 'D', 6)        # PASSWORD
    press(ev, 3400, 1, 'S', 10)
    enter_password(ev, code, 3700)
    press_pair(ev, 4500, 1)           # past the area map, mostly
    for step in plan:
        f = step['frame']
        if step['do'] == 'start':
            press(ev, f, 1, 'S', 6)
        elif step['do'] == 'kill':
            for s in range(1, 20):
                energy(ev, f, s, 0)
            if step.get('hits'):
                energy(ev, f, 0, 0x7F)    # the player: 0x7F hits
        elif step['do'] == 'blast':
            # an explosion (cell value 3, func_006E82) in each one's cell,
            # energy 1, not flashing (+0x12): the next hit is the last
            for s, cell in step['hits']:
                energy(ev, f, s, 1)
                poke(ev, f, SLOT + 0x40 * s + 0x12, 0)
                poke(ev, f, 0xFF0000 | cell, 3)
        elif step['do'] == 'walk':
            poke(ev, f, 0xFF0000 | step['floor'], 6)
            poke(ev, f, SLOT + 0x18, step['x'], 4)
            poke(ev, f, SLOT + 0x1A, step['y'], 4)
            press(ev, f + 10, 1, step['dir'], 120)
    return ev


def exits():
    import json
    if not os.path.exists(EXITS):
        return
    names = [n for n, _ in PASSWORDS]
    for name, e in sorted(json.load(open(EXITS)).items()):
        # an area's last stage goes on into the boss stage, whose palette
        # cycle reads its colours from code (func_00AA52, some 325 frames
        # after the stage ends): a SHIFT build is compared up to there
        # a boss's palette cycle starts as it comes in: up to 4800, as
        # tools/shift_check.py's LIMITS for the stage-*-boss scripts
        nxt = names[names.index(name) + 1]
        compare = e['end'] - 1500 + 300 if 'boss' in nxt else None
        ev = exit_events(e['code'], e['plan'])
        end = e['end']
        if 'boss' in name:
            compare = 4800
            # Start on the next area's map: its intro (D_0179CE)
            press_pair(ev, end - 300, 1)
            end += 1500
        write('exit-%s.txt' % name, ev, '''
Normal game from password %s (%s) to the stage's exit, with RAM writes
as tools/find_exits.py found them: in each room the enemies and targets
at energy 0, then the player next to the open gate, walking in, and the
bonus stage and the next stage's card; or the boss and what it brings at
energy 0, explosions on what that doesn't take down, and the next area's
map and intro.  us's timings.''' % (
            e['code'], name), end, compare)


def items():
    """Every item kind picked up once (random play finds a few): stage
    1-1 with its room cleared (tools/find_exits.py's plan), then items in
    the top row, on both sides of the player.  An item is a grid cell of
    5 and an entry in the list at 0xFFAC00 (30 of 4 bytes: kind, 0, the
    cell's column and row; func_0066BE), its kind indexing D_0069B2."""
    import json
    if not os.path.exists(EXITS):
        return
    plan = json.load(open(EXITS))['1-1']['plan']
    kill = [st for st in plan if st['do'] == 'kill'][0]['frame']
    ev = exit_events('2200', [st for st in plan if st['do'] != 'walk'])
    # the player starts at column 3 of row 1 (16 bytes a row here)
    for f, kinds, cols, d in ((kill + 200, range(1, 10), range(4, 13), 'R'),
                              (kill + 500, range(10, 15), range(12, 7, -1),
                               'L')):
        for k, (kind, c) in enumerate(zip(kinds, cols)):
            poke(ev, f, 0xFF989C + 16 + c, 5)
            poke(ev, f, 0xFFAC00 + 4 * k, kind << 24 | c << 8 | 1, 8)
        press(ev, f + 10, 1, d, 250)
    # then use them: bombs kicked, punched and thrown (D_005E6C's states)
    # in the empty room, the player at 0x7F hits
    energy(ev, kill + 800, 0, 0x7F)
    play(ev, random.Random(5), kill + 810, kill + 3300, extra='AABB',
         every=30)
    # the egg among them hatches a Louie (func_004480) of a random type
    # (0-3), its ability one of D_0048F6's: each type in turn, written
    # where the first rider's is (0xFFA96E, 0xA96E - 5 + its slot 5)
    for k, kind in enumerate((0, 1, 3, 4)):
        poke(ev, kill + 700 + 400 * k, 0xFFA96E, kind)
    write('items.txt', ev, '''
Every item kind once: stage 1-1 from its password, its room cleared,
then items 1-9 in the top row to the right of the player and 10-14 on
the way back, written as an item (grid cell 5) and an entry in the list
at 0xFFAC00; then random play with A and B often, the player at 0x7F
hits.  us's timings.''', kill + 3400)


def timeouts():
    """The clock running out (func_00ACA4: 0xA429 minutes, 0xA428
    seconds, 0xA427 tenths), which random play never waits for.  In a
    battle (0x9540 bit 0): set to 1:03 the hurry-up starts at 1:01.0
    (func_00B1A2, blocks closing in), then with both players at 0x7F hits
    0:03 more runs out: TIME UP and the draw (func_00B2A0).  In the
    normal game: 0:03 in stage 1-1, the player's time up (func_00B346)."""
    import json
    def clock(ev, f, m, sec):
        poke(ev, f, 0xFFA429, m)
        poke(ev, f, 0xFFA428, sec)
        poke(ev, f, 0xFFA427, 0)
    # battle.txt's first match is on by 6800; no play after
    ev = [e for e in battle_events(2, (1, 2)) if e[0] < 6800]
    clock(ev, 6800, 1, 3)
    for s in (0, 1):
        energy(ev, 6800, s, 0x7F)
    clock(ev, 7100, 0, 3)
    write('timeup-battle.txt', ev, '''
A battle's clock running out: battle.txt to its first match, then the
clock at 1:03 (the hurry-up at 1:01.0), both players at 0x7F hits, and
at 0:03 (TIME UP, the draw).''', 9000)
    if not os.path.exists(EXITS):
        return
    plan = json.load(open(EXITS))['1-1']['plan']
    kill = [st for st in plan if st['do'] == 'kill'][0]['frame']
    ev = exit_events('2200', [st for st in plan if st['do'] == 'start'])
    clock(ev, kill + 60, 0, 3)
    write('timeup-stage.txt', ev, '''
Stage 1-1 with its clock at 0:03: the player's time up, the lost life and
the stage again.  us's timings.''', kill + 1500)


def idle():
    write('idle.txt', [(0, 1, '-')], '''
No input: the intro, the title and whatever the game shows when left
alone (a demo, the intro again).''')


def main():
    os.makedirs(HERE, exist_ok=True)
    normal()
    battle('battle.txt', 2, (1, 2), False)
    battle('battle4.txt', 4, (1, 2, 3, 4), True)
    # EA's 4-Way Play: func_009086 finds it at power-on (0x80C2), and the
    # pads are read through func_00912A
    battle('battle4w.txt', 4, (1, 2, 3, 4), False, True)
    password()
    stages()
    ending()
    exits()
    items()
    arenas()
    timeouts()
    idle()


if __name__ == '__main__':
    main()

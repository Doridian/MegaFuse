#!/usr/bin/env python3
"""Translate the game's 68000 code into Rust (docs/PORT.md).

    tools/recomp/translate.py [OUTDIR]  (crates/game/src/translated by default)

Writes OUTDIR/routines_N.rs (the routines, methods of `Game`),
OUTDIR/families.rs (a call through a pointer: a match from the code
address to the routine) and OUTDIR/mod.rs.  Like asm/ it comes from the
ROM and isn't in the repository; `make port` makes it.
"""
import os
import sys

TOP = os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(TOP, 'tools'))
import disasm  # noqa: E402
from recomp import dataflow, emit, families, ir, routines  # noqa: E402

PER_FILE = 150


def taken_routines(d, p):
    names = set(d.extra) | set(d.jtbl_entries) | set(d.ptrs.values())
    for i in d.insns.values():
        for t, k in i.refs():
            if k == 'imm' and t in d.insns:
                names.add(t)
    names |= set(t for _, t in families.load_calls(d.version))
    return set(a for a in p.routines if a in names)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        TOP, 'crates', 'game', 'src', 'translated')
    d = disasm.analyze('us')
    p = ir.build(d)
    for r in p.routines.values():
        if not (r.error or r.crash):
            r.preserved = dataflow.drop_saves(r, p)
    reset = int.from_bytes(d.rom[4:8], 'big')
    fams = families.families(d, p.routines, 'us', taken_routines(d, p),
                             step=(reset, routines.STEP))
    vectors = [int.from_bytes(d.rom[4 * k:4 * k + 4], 'big')
               for k in range(1, 64)]
    roots = set(v for v in vectors if v in p.routines)
    flow = dataflow.Flow(p, fams)
    flow.solve(roots)
    # the reset routine is called as one of the step's family (Regs)
    em = emit.Emitter(p, flow, roots - {reset})
    os.makedirs(out, exist_ok=True)
    for f in os.listdir(out):
        if f.endswith('.rs'):
            os.remove(os.path.join(out, f))
    entries = sorted(p.routines)
    files = []
    for k in range(0, len(entries), PER_FILE):
        name = 'routines_%02d' % (k // PER_FILE)
        files.append(name)
        with open(os.path.join(out, name + '.rs'), 'w') as f:
            f.write('// generated by tools/recomp/translate.py; do not edit\n'
                    'use crate::{Game, Regs};\n\nimpl Game {\n')
            for e in entries[k:k + PER_FILE]:
                f.write(em.routine(p.routines[e]))
                f.write('\n')
            f.write('}\n')
    with open(os.path.join(out, 'families.rs'), 'w') as f:
        f.write('// generated by tools/recomp/translate.py; do not edit\n'
                'use crate::{Game, Regs};\n\nimpl Game {\n')
        for k, (sites, members) in enumerate(flow.fams):
            f.write('    /// Called through a pointer at %s.\n' % (
                ', '.join('%06X' % s for s in sorted(sites)) or
                '(no site the traces saw)'))
            f.write('    pub fn call_family_%d(&mut self, target: u32, regs: '
                    '&mut Regs) {\n        match target & 0xFF_FFFF {\n' % k)
            for m in sorted(members):
                r = p.routines[m]
                if m in roots or not em.is_family(m):
                    continue
                f.write('            0x%06X => self.%s(regs),\n' % (
                    m, emit.fname(m)))
            f.write('            _ => panic!("no routine at {target:#08X} '
                    'among those called from %s"),\n        }\n    }\n' % (
                        ', '.join('%06X' % s for s in sorted(sites))))
        f.write('    pub fn call_family_any(&mut self, target: u32, _regs: '
                '&mut Regs) {\n        panic!("a call through a pointer no '
                'trace saw: {target:#08X}");\n    }\n')
        f.write('}\n')
    # every routine callable by its address, for tests against the
    # original (tools/routine_check.py)
    with open(os.path.join(out, 'by_address.rs'), 'w') as f:
        f.write('// generated by tools/recomp/translate.py; do not edit\n'
                'use crate::{Game, Regs};\n\nimpl Game {\n'
                '    /// Calls the routine at `entry` with its arguments from\n'
                '    /// `regs` and its results back there; false when it takes\n'
                '    /// what `Regs` can\'t give (stack arguments).\n'
                '    #[allow(clippy::all)]\n'
                '    pub fn call_by_address(&mut self, entry: u32, regs: &mut Regs) '
                '-> bool {\n        match entry {\n')
        outs = {}
        for e in entries:
            r = p.routines[e]
            if r.crash or r.error or e in roots:
                continue
            if em.is_family(e):
                f.write('            0x%06X => self.%s(regs),\n' % (e, emit.fname(e)))
                outs[e] = emit.sorted_res(flow.fam_out[flow.fam_of[e]])
                continue
            params = em.params(r)
            if any(n.startswith('arg') or n == 'ret' for n, _ in params):
                continue
            res = em.results(r)
            call = 'self.%s(%s)' % (emit.fname(e), ', '.join(
                'regs.%s' % n for n, _ in params))
            names = ['regs.%s' % ('unwound' if n == 'unwound' else n)
                     for n, _ in res]
            if not names:
                stmt = '%s;' % call
            elif len(names) == 1:
                stmt = '%s = %s;' % (names[0], call)
            else:
                stmt = '(%s) = %s;' % (', '.join(names), call)
            f.write('            0x%06X => { %s }\n' % (e, stmt))
            outs[e] = [n for n, _ in res if n != 'unwound']
        f.write('            _ => return false,\n        }\n        true\n    }\n\n')
        f.write('    /// The registers and flags the routine at `entry` gives back.\n'
                '    #[must_use]\n    pub fn routine_outputs(entry: u32) -> &\'static '
                '[&\'static str] {\n        match entry {\n')
        for e, o in outs.items():
            f.write('            0x%06X => &[%s],\n' % (e, ', '.join('"%s"' % x for x in o)))
        f.write('            _ => &[],\n        }\n    }\n}\n')
    with open(os.path.join(out, 'mod.rs'), 'w') as f:
        f.write('// generated by tools/recomp/translate.py; do not edit\n')
        # the translation's own style (each routine allows the rest)
        f.write('#![allow(unused_parens, unused_comparisons)]\n\n')
        for name in files + ['families', 'by_address']:
            f.write('mod %s;\n' % name)
        reset = int.from_bytes(d.rom[4:8], 'big')
        f.write('\n/// The reset routine (the vector at 4).\n')
        f.write('pub const RESET: u32 = 0x%06X;\n\n' % reset)
        f.write('impl crate::Game {\n    /// The reset routine, to the main '
                'loop (the jump to it returns).\n    pub(crate) fn call_reset('
                '&mut self, regs: &mut crate::Regs) {\n        self.%s(regs);'
                '\n    }\n\n' % emit.fname(reset))
        f.write('    /// A pass of the main loop (routines.STEP).\n'
                '    pub(crate) fn call_step(&mut self, regs: &mut crate::Regs) {\n'
                '        self.%s(regs);\n    }\n\n' % emit.fname(routines.STEP))
        f.write('    /// The handler of interrupt level (the vectors at 0x60 '
                'on).\n    pub(crate) fn call_interrupt(&mut self, level: '
                'u8) {\n        match level {\n')
        for lv in range(1, 8):
            v = int.from_bytes(d.rom[0x60 + 4 * lv:0x64 + 4 * lv], 'big')
            if v in p.routines:
                f.write('            %d => self.%s(),\n' % (lv, emit.fname(v)))
        f.write('            _ => {}\n        }\n    }\n}\n')
    print('%d routines, %d families, %d files' % (
        len(entries), len(flow.fams), len(files)))


if __name__ == '__main__':
    main()

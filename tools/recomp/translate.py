#!/usr/bin/env python3
"""Translate the game's 68000 code into Rust (docs/PORT.md).

    tools/recomp/translate.py [OUTDIR]  (crates/game/src/translated by default)

Writes OUTDIR/routines_N.rs (the routines, methods of `Game`),
OUTDIR/families.rs (a call through a pointer: a match from the code
address to the routine) and OUTDIR/mod.rs.  Like asm/ it comes from the
ROM and isn't in the repository; `make port` makes it.
"""
import os
import sys

TOP = os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(TOP, 'tools'))
import disasm  # noqa: E402
from recomp import dataflow, emit, families, ir  # noqa: E402

PER_FILE = 150


def taken_routines(d, p):
    names = set(d.extra) | set(d.jtbl_entries) | set(d.ptrs.values())
    for i in d.insns.values():
        for t, k in i.refs():
            if k == 'imm' and t in d.insns:
                names.add(t)
    names |= set(t for _, t in families.load_calls(d.version))
    return set(a for a in p.routines if a in names)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        TOP, 'crates', 'game', 'src', 'translated')
    d = disasm.analyze('us')
    p = ir.build(d)
    for r in p.routines.values():
        if not (r.error or r.crash):
            dataflow.drop_saves(r, p)
    fams = families.families(d, p.routines, 'us', taken_routines(d, p))
    vectors = [int.from_bytes(d.rom[4 * k:4 * k + 4], 'big')
               for k in range(1, 64)]
    roots = set(v for v in vectors if v in p.routines)
    flow = dataflow.Flow(p, fams)
    flow.solve(roots)
    em = emit.Emitter(p, flow, roots)
    os.makedirs(out, exist_ok=True)
    for f in os.listdir(out):
        if f.endswith('.rs'):
            os.remove(os.path.join(out, f))
    entries = sorted(p.routines)
    files = []
    for k in range(0, len(entries), PER_FILE):
        name = 'routines_%02d' % (k // PER_FILE)
        files.append(name)
        with open(os.path.join(out, name + '.rs'), 'w') as f:
            f.write('// generated by tools/recomp/translate.py; do not edit\n'
                    'use crate::{Game, Regs};\n\nimpl Game {\n')
            for e in entries[k:k + PER_FILE]:
                f.write(em.routine(p.routines[e]))
                f.write('\n')
            f.write('}\n')
    with open(os.path.join(out, 'families.rs'), 'w') as f:
        f.write('// generated by tools/recomp/translate.py; do not edit\n'
                'use crate::{Game, Regs};\n\nimpl Game {\n')
        for k, (sites, members) in enumerate(flow.fams):
            f.write('    /// Called through a pointer at %s.\n' % (
                ', '.join('%06X' % s for s in sorted(sites)) or
                '(no site the traces saw)'))
            f.write('    pub fn call_family_%d(&mut self, target: u32, regs: '
                    '&mut Regs) {\n        match target & 0xFF_FFFF {\n' % k)
            for m in sorted(members):
                r = p.routines[m]
                if m in roots or not em.is_family(m):
                    continue
                f.write('            0x%06X => self.%s(regs),\n' % (
                    m, emit.fname(m)))
            f.write('            _ => panic!("no routine at {target:#08X} '
                    'among those called from %s"),\n        }\n    }\n' % (
                        ', '.join('%06X' % s for s in sorted(sites))))
        f.write('    pub fn call_family_any(&mut self, target: u32, _regs: '
                '&mut Regs) {\n        panic!("a call through a pointer no '
                'trace saw: {target:#08X}");\n    }\n')
        f.write('}\n')
    with open(os.path.join(out, 'mod.rs'), 'w') as f:
        f.write('// generated by tools/recomp/translate.py; do not edit\n')
        for name in files + ['families']:
            f.write('mod %s;\n' % name)
        reset = int.from_bytes(d.rom[4:8], 'big')
        f.write('\n/// The reset routine (the vector at 4).\n')
        f.write('pub const RESET: u32 = 0x%06X;\n\n' % reset)
        f.write('impl crate::Game {\n    pub(crate) fn call_reset(&mut self) '
                '{\n        self.%s();\n    }\n}\n' % emit.fname(reset))
    print('%d routines, %d families, %d files' % (
        len(entries), len(flow.fams), len(files)))


if __name__ == '__main__':
    main()
